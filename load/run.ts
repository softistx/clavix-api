#!/usr/bin/env bun
import { mkdir, realpath, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
// Load test of a production-like stack on one machine (docs/operations.md,
// "Load test"). Usage: bun load/run.ts <build|up|seed|k6|down|all> [OUT_DIR]
// (`k6` takes the script as its third argument: bun load/run.ts k6 <out> <script>).
//
// The stack is deploy/compose.yml as it is (production mode, resource limits,
// one-node replica set, redis with a password), project `clavix-load`: mongo,
// redis and api only. Caddy and the ui are not started: the api is reached over
// the compose network, with the Host and X-Forwarded-* headers Caddy would send.
// Nothing is published on the host. `down` removes the containers AND the
// volumes of this project only, and the generated deploy/.env.
import { $ } from "bun";

const ROOT = resolve(dirname(import.meta.path), "..");
process.chdir(ROOT);
const P = "clavix-load";
const ENVFILE = `${ROOT}/deploy/.env`;
const MARKER = "# generated by load/run.ts";
const OLD_MARKER = "# generated by load/run.sh";
const USAGE =
  "usage: bun load/run.ts build|up|seed|k6 <out> <script>|down|all [out]";

const phase = process.argv[2] ?? "all";
if (phase === "--help" || phase === "-h") {
  console.log(USAGE);
  process.exit(0);
}

const outArg = process.argv[3] ?? `${ROOT}/load/out`;
let OUT = outArg;
if (phase !== "down" && phase !== "build" && phase !== "up") {
  await mkdir(outArg, { recursive: true });
  OUT = await realpath(outArg);
}

const rand = async (kind: "hex" | "base64", bytes: number) =>
  (await $`openssl rand -${kind} ${bytes}`.text()).trim();

// docker compose for the load project; `args` are passed as separate words.
const dc = (args: string[]) =>
  $`docker compose -p ${P} -f deploy/compose.yml --env-file ${ENVFILE} ${args}`;

const build = async () => {
  await $`docker build -t clavix-api:load ${ROOT}`;
};

const up = async () => {
  if (await Bun.file(ENVFILE).exists()) {
    console.error(`refusing to overwrite ${ENVFILE}`);
    process.exit(1);
  }
  const env = `${MARKER}
CLAVIX_API_IMAGE=clavix-api:load
CLAVIX_UI_IMAGE=unused:never-started
CLAVIX_DOMAIN=clavix.test
ACME_EMAIL=load@clavix.test
REDIS_PASSWORD=${await rand("hex", 24)}
MONGO_ROOT_USER=root
MONGO_ROOT_PASSWORD=${await rand("hex", 24)}
MONGO_APP_USER=clavix
MONGO_APP_PASSWORD=${await rand("hex", 24)}
MONGO_KEYFILE=${await rand("hex", 64)}
CLAVIX_KEYS_MASTER_KEY=${await rand("base64", 32)}
CLAVIX_TLS_ASK_SECRET=${await rand("hex", 32)}
CONSOLE_CLIENT_SECRET=pending-db-migrate
CLAVIX_SMTP_URL=smtps://load:load@smtp.invalid:465
CONSOLE_SESSION_SECRET=${await rand("base64", 48)}
`;
  await writeFile(ENVFILE, env, { mode: 0o600 });
  await dc(["up", "-d", "--wait", "mongo", "redis"]);
  await dc(["run", "--rm", "-T", "api", "bun", "run", "db:sync"]);
  await dc(["run", "--rm", "-T", "api", "bun", "run", "db:migrate"]);
};

const seed = async () => {
  // 50 tenants, 2 refresh chains each = 100 chains, one per k6 VU of token.js.
  const out = await dc([
    "run",
    "--rm",
    "-T",
    "-v",
    `${ROOT}/load:/app/load:ro`,
    "api",
    "bun",
    "load/seed.ts",
  ]).text();
  const last = out.replace(/\n$/, "").split("\n").at(-1) ?? "";
  await Bun.write(`${OUT}/seed.json`, `${last}\n`);
  await dc(["up", "-d", "--wait", "api"]);
  // Warm: the api builds each tenant's server on its first request.
  const s = JSON.parse(await Bun.file(`${OUT}/seed.json`).text());
  console.log(
    `seeded: ${s.tenants.length} tenants ${s.tenants.length * s.tenants[0].chains.length} chains`,
  );
};

// Returns k6's exit code. RATE, VUS, DURATION, WARMUP and CLIENT_CREDENTIALS
// pass through when set (`-e NAME` copies the variable from the environment).
const k6 = async (script: string): Promise<number> => {
  const name = script.replace(/\.js$/, "");
  const r =
    await $`docker run --rm --network ${P}_default -v ${ROOT}/load:/load:ro -v ${OUT}:/out -e SEED_FILE=/out/seed.json -e BASE_URL=http://api:3000 -e RATE -e VUS -e DURATION -e WARMUP -e CLIENT_CREDENTIALS grafana/k6 run --quiet --summary-export ${`/out/${name}.summary.json`} ${`/load/${script}`} 2>&1`
      .quiet()
      .nothrow();
  const text = r.stdout.toString();
  process.stdout.write(text);
  await Bun.write(`${OUT}/${name}.log`, text);
  return r.exitCode;
};

const down = async () => {
  await dc(["down", "-v", "--remove-orphans"]).nothrow();
  const first = (await Bun.file(ENVFILE).exists())
    ? ((await Bun.file(ENVFILE).text()).split("\n")[0] ?? "")
    : "";
  if (first === MARKER || first === OLD_MARKER)
    await rm(ENVFILE, { force: true });
  else console.log(`${ENVFILE} is not the generated one: left in place`);
};

switch (phase) {
  case "build":
    await build();
    break;
  case "up":
    await up();
    break;
  case "seed":
    await seed();
    break;
  case "k6": {
    const script = process.argv[4];
    if (!script) {
      console.error("k6: script required");
      process.exit(1);
    }
    process.exit(await k6(script));
    break;
  }
  case "down":
    await down();
    break;
  case "all": {
    let rc = 0;
    try {
      await build();
      await up();
      await seed();
      const a = await k6("jwks-discovery.js");
      await seed();
      const b = await k6("token.js");
      rc = b || a;
    } catch (e) {
      console.error(e);
      rc = 1;
    } finally {
      await down();
    }
    process.exit(rc);
    break;
  }
  default:
    console.error(USAGE);
    process.exit(2);
}
